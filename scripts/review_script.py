import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

try:
    from .llm_provider import generate_content, get_api_key
except ImportError:
    from llm_provider import generate_content, get_api_key

try:
    from .quality_checks import analyze_script, render_report
except ImportError:
    from quality_checks import analyze_script, render_report

try:
    from .source_notes import load_optional_source_notes
except ImportError:
    from source_notes import load_optional_source_notes

MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash-lite")
API_URL = f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL}:generateContent"


def main():
    if len(sys.argv) < 2:
        raise SystemExit("Usage: review_script.py SCRIPT_PATH [SOURCE_NOTES]")

    script_path = Path(sys.argv[1])
    source_notes = load_optional_source_notes(sys.argv[2] if len(sys.argv) > 2 else None)
    try:
        api_key = get_api_key()
    except RuntimeError as exc:
        raise SystemExit(str(exc)) from exc
    if not script_path.is_file():
        raise SystemExit(f"Script file not found: {script_path}")

    script = script_path.read_text(encoding="utf-8")
    content_format = os.environ.get("SCRIPT_FORMAT", "Concept Explainer")
    language = os.environ.get("SCRIPT_LANGUAGE", "Bilingual")
    review_stage = re.sub(r"[^a-z0-9-]+", "-", os.environ.get("REVIEW_STAGE", "review").lower()).strip("-") or "review"

    deterministic_findings = analyze_script(script, content_format, language)
    deterministic_report = render_report(script, deterministic_findings, content_format, language)
    blocking_findings = [item for item in deterministic_findings if item["blocking"]]

    system_prompt = """You are a strict academic quality reviewer for DigvijayEconLab,
serving MPPSC Assistant Professor Economics aspirants.
Review the supplied draft; do not rewrite it and do not add outside facts.
Treat the supplied script and source notes as the only evidence available.
Do not claim that a statement is verified unless the supplied source notes support it.
If source notes are absent, explicitly say independent textbook/source verification is still required.
Check: conceptual accuracy and internal consistency; definitions and assumptions;
correct use of economic terminology; Hindi-English equivalence and clarity;
examples and exceptions; MCQ option quality, answer correctness and explanations;
unsupported claims, fabricated references, and every [VERIFY] marker;
exam-level depth, teaching sequence, and narration readiness.
Severity calibration is mandatory: Critical/High are reserved for substantive economic errors,
incorrect answers, unsupported material factual assertions presented as established facts,
or translation failures that change or materially obscure economic meaning. Grammar, headings,
stylistic consistency, and punctuation are normally Medium/Low unless they create material ambiguity.
Explicit [VERIFY] markers and the absence of supplied source notes are intentional human-review
flags, not by themselves Critical/High content defects and not reasons to prevent handoff to
a subject-matter reviewer. List them under Verification Gaps and retain the marker text in
the draft. Do not claim that the underlying claim is verified. If a material factual assertion
is unqualified and lacks evidence, flag that assertion as High and explain what source is needed.
For each issue give severity (Critical/High/Medium/Low), exact quoted phrase or section,
why it needs attention, and a concrete correction direction without inventing facts.
If no substantive Critical or High issue remains, state READY FOR HUMAN REVIEW even when
verification markers and Medium/Low editorial recommendations remain. This verdict is never
publication approval; every [VERIFY] marker must be resolved by a human before public release.
Separate source-supported observations from general academic concerns.
The user-selected content format and language are supplied with the script. Apply the
format-specific content requirements and explicitly audit bilingual translation parity.
Never treat presence of both scripts as proof that the translations are equivalent.
The appended deterministic check report is generated by local Python checks. Do not
ignore, downgrade, or contradict any finding in that report. If it contains one or more
blocking findings, the final verdict MUST be HOLD FOR CORRECTION, regardless of your
own assessment. Non-blocking verification-marker findings must be listed under Verification
Gaps and must not alone force a HOLD. If no blocking findings or substantive Critical/High
issues remain, use READY FOR HUMAN REVIEW. Human fact-checking and publication approval
remain mandatory. This is an advisory review, not a factual certification.
Return readable Markdown with sections: Overall Verdict, Critical Issues,
High-Priority Issues, Other Improvements, MCQ Audit, Verification Gaps,
and Pre-Production Checklist."""

    unit_context = os.environ.get("SCRIPT_UNIT", "Not specified")
    user_prompt = f"""UNIT: {unit_context}\n\nSOURCE NOTES (may be empty):
{source_notes if source_notes.strip() else "[No source notes supplied. Do not certify factual claims.]"} 

SELECTED FORMAT: {content_format}
SELECTED LANGUAGE: {language}

DETERMINISTIC CHECK REPORT (machine-generated; blocking findings must be respected):
{deterministic_report}

SCRIPT TO REVIEW:
{script}"""

    payload = {
        "systemInstruction": {"parts": [{"text": system_prompt}]},
        "contents": [{"role": "user", "parts": [{"text": user_prompt}]}],
        "generationConfig": {"temperature": 0.2, "maxOutputTokens": 8192},
    }
    try:
        result = generate_content(API_URL, api_key, payload, label="Academic review", timeout=120)
    except RuntimeError as exc:
        raise SystemExit(str(exc)) from exc

    candidates = result.get("candidates", [])
    if not candidates:
        raise SystemExit("Gemini returned no review candidate.")
    parts = candidates[0].get("content", {}).get("parts", [])
    review = "\n".join(part.get("text", "") for part in parts if part.get("text"))
    if not review.strip():
        raise SystemExit("Gemini returned an empty quality review.")

    gate_override = (
        "\n\n## Deterministic Gate Override\n\n"
        "**FINAL VERDICT: HOLD FOR CORRECTION.**\n\n"
        f"The local deterministic gate detected {len(blocking_findings)} blocking finding(s). "
        "These findings cannot be overridden by the AI review. Resolve them and rerun the review.\n"
        if blocking_findings else
        "\n\n## Deterministic Gate Status\n\n"
        "**No blocking structural findings detected.** This is not an academic fact-check; "
        "subject-matter verification and human approval remain mandatory.\n"
    )

    output_dir = Path("output/reviews")
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{script_path.stem}-quality-review.md"
    output_path.write_text(
        "# Academic Quality-Control Report\n\n"
        "> AI-assisted review only. Not a factual certification. Human verification and approval are mandatory.\n\n"
        + review.strip() + gate_override + "\n",
        encoding="utf-8",
    )

    check_dir = Path("output/quality_checks")
    check_dir.mkdir(parents=True, exist_ok=True)
    check_path = check_dir / f"{script_path.stem}-{review_stage}-deterministic-check.md"
    check_path.write_text(deterministic_report, encoding="utf-8")

    print(f"Quality review generated: {output_path}")
    print(f"Deterministic quality report generated: {check_path}")
    if blocking_findings:
        print(f"QUALITY GATE: HOLD FOR CORRECTION ({len(blocking_findings)} blocking finding(s)).")
    else:
        print("QUALITY GATE: No blocking structural findings; human review remains mandatory.")
    print("Status: ADVISORY ONLY — original script unchanged; human review required.")


if __name__ == "__main__":
    main()
